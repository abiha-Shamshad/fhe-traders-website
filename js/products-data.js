//                                            js/variants.js generates from the
//                                            number in the label.
//
//   { label: "6kW",                          label plus this variant's OWN data.
//     image: "images/products/variants/crown-micro-6kw.jpg",
//     specs: ["Rated output: 6000W",
//             "System voltage: 48V", ...],
//     desc:  "Optional paragraph." }         Selecting the chip swaps in this
